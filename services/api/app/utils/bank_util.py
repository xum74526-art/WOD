def luhn_check(card_number: str) -> bool:
    """Luhn算法校验银行卡号（最后一位为校验位）"""
    # 去除空格和非数字字符
    num = "".join(c for c in card_number if c.isdigit())
    if len(num) < 12 or len(num) > 19:
        return False
    total = 0
    reverse = num[::-1]
    for i, ch in enumerate(reverse):
        n = int(ch)
        if i % 2 == 1:  # 偶数位（从0开始）
            n *= 2
            if n > 9:
                n -= 9
        total += n
    return total % 10 == 0


def detect_bank(card_number: str) -> str | None:
    """根据无冲突 BIN 给出银行名称建议，不代表银行验证。"""
    num = "".join(c for c in card_number if c.isdigit())
    if len(num) < 6:
        return None
    prefix = num[:6]
    if prefix in AMBIGUOUS_BANK_BINS:
        return None
    if prefix in BANK_BINS:
        return BANK_BINS[prefix]
    return None


def validate_phone(phone: str) -> bool:
    """中国手机号格式校验"""
    if not phone:
        return True  # 选填，空值通过
    return phone.startswith("1") and len(phone) == 11 and phone.isdigit()
