// Some pages keep their option arrays in Chinese and pass the visible label to
// `t()`. Build the reverse lookup from both dictionaries so those labels resolve
// just like semantic keys do. Previously only generated keys were included,
// which left core labels such as "推荐", "运行中" and "我的订单" in Chinese.
const EN_BY_ZH: Record<string, string> = Object.keys(ZH).reduce((result, key) => {
  result[ZH[key]] = EN[key] ?? ZH[key]
  return result
}, {} as Record<string, string>)

Object.keys(ZH_GEN).forEach((key) => {
  EN_BY_ZH[ZH_GEN[key]] = EN_GEN[key]
})

const PARTIAL_EN = Object.entries({ ...EN_BY_ZH, ...EXTRA_EN })
  .filter(([source]) => source.length >= 2)
  .sort(([a], [b]) => b.length - a.length)

const TRANSLATION_KEY_BY_TEXT = new Map<string, string>()

function registerTranslationText(text: string, key: string) {
  if (text && !TRANSLATION_KEY_BY_TEXT.has(text)) TRANSLATION_KEY_BY_TEXT.set(text, key)
}

for (const [key, value] of Object.entries(ZH)) {
  registerTranslationText(key, key)
  registerTranslationText(value, key)
  registerTranslationText(toTraditionalChinese(value), key)
}
for (const [key, value] of Object.entries(EN)) registerTranslationText(value, key)
for (const [key, value] of Object.entries(ZH_GEN)) {
  registerTranslationText(key, key)
  registerTranslationText(value, key)
  registerTranslationText(toTraditionalChinese(value), key)
}
for (const [key, value] of Object.entries(EN_GEN)) registerTranslationText(value, key)
for (const [source, value] of Object.entries(EXTRA_EN)) {
  registerTranslationText(source, source)
  registerTranslationText(toTraditionalChinese(source), source)
  registerTranslationText(value, source)
}

function interpolate(text: string, params?: Params): string {
  if (!params) return text
  return Object.entries(params).reduce(
    (result, [key, value]) => result.replace(new RegExp(`\\{${key}\\}`, 'g'), String(value)),
    text,
  )
}

function translateDynamicText(source: string): string | null {
  let match = source.match(/^再消费\s*([\d,.]+)\s*卡时可升至\s*([\d.]+)%\s*返佣$/)
  if (match) return `Spend ${match[1]} more CH to reach a ${match[2]}% rebate`

  match = source.match(/^再销售\s*([\d,.]+)\s*卡时可升至\s*([\d.]+)%\s*返佣$/)
  if (match) return `Sell ${match[1]} more CH to reach a ${match[2]}% rebate`

  match = source.match(/^已达最高返佣等级\s*([\d.]+)%$/)
  if (match) return `Highest rebate tier reached: ${match[1]}%`

  match = source.match(/^再邀请\s*([\d,.]+)\s*人升级至\s*([\d.]+)%\s*返利$/)
  if (match) return `Invite ${match[1]} more people to reach a ${match[2]}% reward rate`

  if (source === '已达最高返利等级') return 'Highest invitation reward tier reached'

  return null
}

export const useI18nStore = defineStore('i18n', () => {
  const saved = uni.getStorageSync('xod-lang')
  const lang = ref<Lang>(normalizeStoredLanguage(saved))
  const locale = computed(() => languageLocale(lang.value))

  // Numeric formatters also render localized CH units. Synchronize them with
  // the reactive language state so switching language never requires reload.
  watch(lang, setFormatLanguage, { immediate: true })

  function updateTabBar() {
    const tabs = ['tabHome', 'tabMarket', 'tabCommunity', 'tabAssets', 'tabProfile']
    tabs.forEach((key, index) => {
      try {
        uni.setTabBarItem({ index, text: t(key), fail: () => {} })
      } catch {}
    })
  }

  function init() {
    applyLocale()
    // onLaunch can run before uni-app's locale service is ready on H5.
    setTimeout(() => {
      // #ifdef H5
      applyLocale()
      // #endif
      updateTabBar()
    }, 100)
  }

  function toggle() {
    setLanguage(nextLanguage(lang.value))
  }

  function setLanguage(language: Lang) {
    lang.value = language
    uni.setStorageSync('xod-lang', lang.value)
    applyLocale()
    updateTabBar()
  }

  function applyLocale() {
    const targetLocale = languageDocumentTag(lang.value)
    // The visible App UI is driven by the reactive `lang` state above.
    // Do not call uni.setLocale here: on Android App it restarts the native
    // runtime, so a language toggle would close and reopen the application.
    // #ifdef H5
    if (typeof window !== 'undefined') window.localStorage.setItem('UNI_LOCALE', targetLocale)
    if (typeof document !== 'undefined') document.documentElement.lang = targetLocale
    // #endif
  }

  const dict = computed(() => lang.value === 'en' ? EN : ZH)

  function t(key: string, params?: Params): string {
    const simplified = ZH[key] ?? ZH_GEN[key] ?? key
    if (lang.value === 'en') {
      return interpolate(EN[key] ?? EXTRA_EN[key] ?? EN_GEN[key] ?? EN_BY_ZH[key] ?? key, params)
    }
    const value = interpolate(simplified, params)
    return lang.value === 'zh-Hant' ? toTraditionalChinese(value) : value
  }

  function tr(value: unknown): string {
    const source = value == null ? '' : String(value)
    if (!source || lang.value === 'zh-Hans') return source
    if (lang.value === 'zh-Hant') return toTraditionalChinese(source)
    const exact = t(source)
    if (exact !== source) return exact
    const dynamic = translateDynamicText(source)
    if (dynamic) return dynamic
    return PARTIAL_EN.reduce(
      (result, [zh, en]) => result.includes(zh) ? result.split(zh).join(en) : result,
      source,
    )
  }

  function localizedErrorMessage(
    cause: unknown,
    fallbackKey: string,
    aliases: Readonly<Record<string, string>> = {},
  ): string {
    const source = cause instanceof Error ? cause.message.trim() : ''
    const key = aliases[source] || TRANSLATION_KEY_BY_TEXT.get(source)
    return t(key || fallbackKey)
  }

  return { lang, locale, init, toggle, setLanguage, updateTabBar, t, tr, localizedErrorMessage }
})
